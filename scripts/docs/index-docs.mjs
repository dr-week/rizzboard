import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, '../..');
const DOCS_DIR = path.join(REPO_ROOT, 'docs');
const INDEX_OUT = path.join(DOCS_DIR, 'INDEX.md');

function collectDocs(dir, relBase = '') {
  const entries = [];
  for (const item of fs.readdirSync(dir, { withFileTypes: true })) {
    if (item.name === 'INDEX.md') continue;
    const full = path.join(dir, item.name);
    const rel = relBase ? `${relBase}/${item.name}` : item.name;
    if (item.isDirectory()) {
      entries.push(...collectDocs(full, rel));
    } else if (item.name.endsWith('.md')) {
      const firstLine = fs.readFileSync(full, 'utf8').split('\n').find(l => l.startsWith('# ')) || item.name;
      const title = firstLine.replace(/^#\s*/, '').trim();
      const category = relBase || 'root';
      entries.push({ category, rel, title });
    }
  }
  return entries;
}

const docs = collectDocs(DOCS_DIR);
const byCategory = new Map();
for (const doc of docs) {
  if (!byCategory.has(doc.category)) byCategory.set(doc.category, []);
  byCategory.get(doc.category).push(doc);
}

const lines = [
  '# RizzBoard Documentation Index',
  '',
  `*Auto-generated by \`scripts/docs/index-docs.mjs\` — ${docs.length} documents indexed.*`,
  ''
];

for (const [cat, items] of Array.from(byCategory.entries()).sort()) {
  lines.push(`## ${cat.charAt(0).toUpperCase() + cat.slice(1)}`);
  for (const item of items.sort((a, b) => a.rel.localeCompare(b.rel))) {
    lines.push(`- [${item.title}](./${item.rel})`);
  }
  lines.push('');
}

fs.writeFileSync(INDEX_OUT, lines.join('\n'));
console.log(`✓ Indexed ${docs.length} documentation files -> docs/INDEX.md`);
